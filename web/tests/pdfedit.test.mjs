// The PDF engine, checked against the one it was ported from.
//
// A PDF is a graph of numbered objects whose cross-reference table is a list
// of byte offsets into the file. Asserting that the output "looks like a PDF"
// would miss exactly the mistakes a port makes: an object numbered differently,
// a dictionary key in another order, an offset off by one. So every case is
// built by both implementations and the bytes compared.
//
// Byte-identical is a strong claim, and it is the right one here: the Python
// writer emits objects in a deterministic order, so anything else means the
// port has drifted.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  PDF, PdfError, build, buildWithout, pageCount, parseRanges, invertRanges,
} from '../js/pdfedit.js';

const SRC = fileURLToPath(new URL('../../src', import.meta.url));
const TESTS = fileURLToPath(new URL('../../tests', import.meta.url));
const spec = JSON.parse(readFileSync(
  fileURLToPath(new URL('../../shared/spec/page-ranges.json', import.meta.url)), 'utf8'));

let python = true;
try { execFileSync('python3', ['-c', 'pass'], { stdio: 'ignore' }); } catch { python = false; }
const needsPython = python ? false : 'python3 not available';

/** Run a snippet with src/ and tests/ importable; returns its stdout. */
function py(code, input = '') {
  return execFileSync('python3', ['-c', `
import base64, sys
sys.path.insert(0, ${JSON.stringify(SRC)})
sys.path.insert(0, ${JSON.stringify(TESTS)})
${code}
`], { input, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
}

/** PDFs generated by the Python test helpers, so both sides see one fixture. */
function fixtures() {
  const out = py(`
import base64, helpers
made = {
  'plain3':   helpers.make_pdf(('One', 'Two', 'Three')),
  'plain1':   helpers.make_pdf(('Only',)),
  'plain8':   helpers.make_pdf(tuple('Page %d' % i for i in range(1, 9))),
  'modern5':  helpers.make_modern_pdf(('A', 'B', 'C', 'D', 'E')),
}
sys.stdout.write('\\n'.join(k + ':' + base64.b64encode(v).decode() for k, v in made.items()))
`);
  const map = new Map();
  for (const line of out.trim().split('\n')) {
    const i = line.indexOf(':');
    map.set(line.slice(0, i), new Uint8Array(Buffer.from(line.slice(i + 1), 'base64')));
  }
  return map;
}

const FIX = python ? fixtures() : new Map();
const b64 = bytes => Buffer.from(bytes).toString('base64');

/** Build the same job in Python and return its bytes. */
function pythonBuild(parts, { without = false } = {}) {
  const payload = JSON.stringify(parts.map(([name, spec]) => [b64(FIX.get(name)), spec]));
  const out = py(`
import json
from convertly import pdfedit
parts = [(base64.b64decode(d), s) for d, s in json.loads(sys.stdin.read())]
fn = pdfedit.build_without if ${without ? 'True' : 'False'} else pdfedit.build
sys.stdout.write(base64.b64encode(fn(parts)).decode())
`, payload);
  return new Uint8Array(Buffer.from(out, 'base64'));
}

// --- page ranges, from the shared spec -------------------------------------

test('page ranges match the shared spec', () => {
  for (const c of spec.valid) {
    assert.deepEqual(parseRanges(c.spec, c.total), c.pages,
      `${JSON.stringify(c.spec)} of ${c.total}${c.why ? ` (${c.why})` : ''}`);
  }
  assert.ok(spec.valid.length >= 15, 'the spec should be covering real ground');
});

test('a refused range says which part was wrong', () => {
  for (const c of spec.invalid) {
    let message = null;
    try {
      parseRanges(c.spec, c.total);
    } catch (err) {
      assert.ok(err instanceof PdfError, `${JSON.stringify(c.spec)} threw ${err}`);
      message = err.message;
    }
    assert.notEqual(message, null,
      `${JSON.stringify(c.spec)} of ${c.total} should be refused${c.why ? ` (${c.why})` : ''}`);
    assert.ok(message.includes(c.message_contains),
      `${JSON.stringify(c.spec)}: ${JSON.stringify(message)} should mention ${JSON.stringify(c.message_contains)}`);
  }
});

test('removing pages is the inverse of keeping them', () => {
  assert.deepEqual(invertRanges('2-4', 10), [1, 5, 6, 7, 8, 9, 10]);
  assert.deepEqual(invertRanges('1', 3), [2, 3]);
  assert.deepEqual(invertRanges('1,3', 4), [2, 4]);
  // Blank means "remove nothing", which is the opposite reason parseRanges
  // gives the same answer for the same input.
  assert.deepEqual(invertRanges('', 3), [1, 2, 3]);
  assert.deepEqual(parseRanges('', 3), [1, 2, 3]);
  assert.throws(() => invertRanges('1-3', 3), /remove every page/);
  assert.throws(() => invertRanges('9', 3), PdfError);
});

// --- reading ---------------------------------------------------------------

test('page counts agree with Python', { skip: needsPython }, () => {
  for (const [name, data] of FIX) {
    const want = Number(py(`
from convertly import pdfedit
sys.stdout.write(str(pdfedit.page_count(base64.b64decode(sys.stdin.read()))))
`, b64(data)));
    assert.equal(pageCount(data), want, name);
  }
});

test('a cross-reference stream PDF is read, not just a classic table', { skip: needsPython }, () => {
  // make_modern_pdf packs its objects into object streams behind an xref
  // stream -- the PDF 1.5 path, which is the half most likely to be got wrong.
  const doc = new PDF(FIX.get('modern5'));
  assert.equal(doc.pageCount(), 5);
  assert.ok([...doc.xref.values()].some(e => e[0] === 'stm'),
    'this fixture should exercise object streams');
});

test('rubbish is refused with a readable message', () => {
  assert.throws(() => pageCount(new Uint8Array([1, 2, 3])), /doesn't look like a PDF/);
  assert.throws(() => pageCount(new TextEncoder().encode('%PDF-1.4\nnothing here')), PdfError);
});

// --- writing, byte for byte ------------------------------------------------

test('extracting pages is byte-identical to Python', { skip: needsPython }, () => {
  const jobs = [
    [['plain3', '']],
    [['plain3', '2']],
    [['plain3', '2-3']],
    [['plain8', '2-4']],
    [['plain8', '1,3,5-7']],
    [['plain8', '2-']],
    [['plain8', '-3']],
    [['plain8', '3-1']],
    [['plain1', 'all']],
    [['modern5', '2-4']],
    [['modern5', '5-1']],
  ];
  for (const job of jobs) {
    const mine = Buffer.from(build(job.map(([n, s]) => [FIX.get(n), s])));
    const theirs = Buffer.from(pythonBuild(job));
    assert.deepEqual(mine, theirs, JSON.stringify(job));
  }
});

test('merging documents is byte-identical to Python', { skip: needsPython }, () => {
  const jobs = [
    [['plain3', ''], ['plain1', '']],
    [['plain1', ''], ['plain3', '']],
    [['plain3', '2-3'], ['plain8', '1']],
    [['plain8', '8-6'], ['modern5', '1-2'], ['plain1', '']],
    [['modern5', ''], ['modern5', '']],
  ];
  for (const job of jobs) {
    const mine = Buffer.from(build(job.map(([n, s]) => [FIX.get(n), s])));
    const theirs = Buffer.from(pythonBuild(job));
    assert.deepEqual(mine, theirs, JSON.stringify(job));
  }
});

test('removing pages is byte-identical to Python', { skip: needsPython }, () => {
  const jobs = [
    [['plain3', '2']],
    [['plain8', '2-4']],
    [['plain8', '1,8']],
    [['modern5', '3']],
    [['plain3', '']],
  ];
  for (const job of jobs) {
    const mine = Buffer.from(buildWithout(job.map(([n, s]) => [FIX.get(n), s])));
    const theirs = Buffer.from(pythonBuild(job, { without: true }));
    assert.deepEqual(mine, theirs, JSON.stringify(job));
  }
});

// --- what the result actually contains -------------------------------------

test('the pages that come out are the ones asked for', { skip: needsPython }, () => {
  // Python reads back what JavaScript wrote, and reports the text on each
  // page. Byte-equality proves the port matches; this proves both are right.
  const made = build([[FIX.get('plain8'), '3-1']]);
  const text = py(`
import helpers
data = base64.b64decode(sys.stdin.read())
sys.stdout.write('|'.join(helpers.page_texts(data)))
`, b64(made));
  assert.equal(text, 'Page 3|Page 2|Page 1', 'order must be exactly as typed');

  const merged = build([[FIX.get('plain3'), '3'], [FIX.get('plain8'), '1-2']]);
  const mergedText = py(`
import helpers
data = base64.b64decode(sys.stdin.read())
sys.stdout.write('|'.join(helpers.page_texts(data)))
`, b64(merged));
  assert.equal(mergedText, 'Three|Page 1|Page 2');

  const without = buildWithout([[FIX.get('plain8'), '2-7']]);
  const withoutText = py(`
import helpers
data = base64.b64decode(sys.stdin.read())
sys.stdout.write('|'.join(helpers.page_texts(data)))
`, b64(without));
  assert.equal(withoutText, 'Page 1|Page 8');
});

test('a produced PDF can be read back by this engine too', { skip: needsPython }, () => {
  const made = build([[FIX.get('plain8'), '2-4'], [FIX.get('plain3'), '1']]);
  assert.equal(pageCount(made), 4);
  // And again, to be sure the output is a fixed point rather than lucky.
  assert.equal(pageCount(build([[made, '']])), 4);
});
